fn test_dd_trig_special_values() {
	shi, slo := sin_dd(0.0)
	assert shi == 0.0 && slo == 0.0
	chi, clo := cos_dd(0.0)
	assert chi == 1.0 && clo == 0.0
	assert math.abs(sin(math.pi / 2) - 1.0) < 1e-15
	assert math.abs(cos(math.pi) + 1.0) < 1e-15
	// Pythagorean identity at double-double accuracy for a large argument.
	h1, l1 := sin_dd(123456.789)
	h2, l2 := cos_dd(123456.789)
	s := (h1 + l1) * (h1 + l1) + (h2 + l2) * (h2 + l2)
	assert math.abs(s - 1.0) < 1e-15
}
