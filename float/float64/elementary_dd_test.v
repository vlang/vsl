fn test_dd_elementary_special_values() {
	hi, lo := exp_dd(0.0)
	assert hi == 1.0 && lo == 0.0
	lhi, llo := log_dd(1.0)
	assert lhi == 0.0 && llo == 0.0
	assert math.is_inf(f64(exp(1000.0)), 1)
	assert exp(-1000.0) == 0.0
	assert math.is_inf(f64(log(0.0)), -1)
	assert math.is_nan(log(-1.0))
	assert math.abs(log(math.e) - 1.0) < 1e-15
	assert math.abs(exp(1.0) - math.e) < 1e-15
}
