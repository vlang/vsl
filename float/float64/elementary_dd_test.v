module float64

import math

// Reference triples [input_bits, hi_bits, lo_bits] generated with mpmath
// at 200 bits of precision: hi is the correctly rounded f64 result and
// lo the correctly rounded residual (exact - hi). exp_dd/log_dd must
// reproduce hi bit for bit, and lo to double-double accuracy.

fn test_exp_dd_matches_correctly_rounded_references() {
	for triple in exp_dd_references {
		x := math.f64_from_bits(triple[0])
		hi, lo := exp_dd(x)
		assert math.f64_bits(hi) == triple[1], 'exp_dd hi bits mismatch for input ${triple[0]}'
		lo_ref := math.f64_from_bits(triple[2])
		tol := 1e-18 * math.max(1.0, math.abs(hi))
		assert math.abs(lo - lo_ref) <= tol, 'exp_dd lo mismatch for input ${triple[0]}: ${lo} vs ${lo_ref}'
		// The scalar wrapper rounds the pair to f64.
		assert exp(x) == hi + lo
	}
}

fn test_log_dd_matches_correctly_rounded_references() {
	for triple in log_dd_references {
		x := math.f64_from_bits(triple[0])
		hi, lo := log_dd(x)
		assert math.f64_bits(hi) == triple[1], 'log_dd hi bits mismatch for input ${triple[0]}'
		lo_ref := math.f64_from_bits(triple[2])
		tol := 1e-28 * math.max(1.0, math.abs(hi))
		assert math.abs(lo - lo_ref) <= tol, 'log_dd lo mismatch for input ${triple[0]}: ${lo} vs ${lo_ref}'
		assert log(x) == hi + lo
	}
}

fn test_dd_elementary_special_values() {
	hi, lo := exp_dd(0.0)
	assert hi == 1.0 && lo == 0.0
	lhi, llo := log_dd(1.0)
	assert lhi == 0.0 && llo == 0.0
	assert math.is_inf(f64(exp(1000.0)), 1)
	assert exp(-1000.0) == 0.0
	assert math.is_inf(f64(log(0.0)), -1)
	assert math.is_nan(log(-1.0))
	assert math.abs(log(math.e) - 1.0) < 1e-15
	assert math.abs(exp(1.0) - math.e) < 1e-15
}
